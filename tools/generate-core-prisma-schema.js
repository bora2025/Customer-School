#!/usr/bin/env node
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const contract = JSON.parse(fs.readFileSync(path.join(root, 'docs/architecture/core-schema-contract.json'), 'utf8'));
const legacyPath = path.join(root, contract.legacy.schemaPath);
const outputPath = path.join(root, contract.freshCore.schemaPath);

function generate() {
  const source = fs.readFileSync(legacyPath, 'utf8');
  const blocks = new Map([...source.matchAll(/model\s+(\w+)\s*\{([\s\S]*?)\n\}/g)]
    .map((match) => [match[1], `model ${match[1]} {${match[2]}\n}`]));
  const removals = new Set(contract.identityFieldSplits);
  const models = contract.freshCore.models.map((name) => {
    const block = blocks.get(name);
    if (!block) throw new Error(`Core model is missing from the legacy compatibility schema: ${name}`);
    const lines = block.split(/\r?\n/).filter((line) => {
      const field = line.trim().match(/^(\w+)\s+/)?.[1];
      return !field || !removals.has(`${name}.${field}`);
    });
    return lines.join('\n');
  });
  return `// GENERATED by tools/generate-core-prisma-schema.js from accepted ownership.\n` +
    `// Do not copy optional business models or edit this file directly.\n\n` +
    `generator client {\n  provider = "prisma-client-js"\n  output   = "../../generated/core-client"\n}\n\n` +
    `datasource db {\n  provider = "postgresql"\n  url      = env("DATABASE_URL")\n}\n\n` +
    `${models.join('\n\n')}\n`;
}

const expected = generate();
if (process.argv.includes('--write')) {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, expected);
  console.log(`Core Prisma schema written to ${path.relative(root, outputPath)}`);
} else if (process.argv.includes('--check')) {
  if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== expected) {
    throw new Error('Core Prisma schema is missing or stale; run npm run schema:core:write');
  }
  console.log(`Core Prisma schema is current (${contract.freshCore.models.length} models)`);
} else {
  process.stdout.write(expected);
}

